import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/');
  await page.locator('.nav-links a[href="/projekty"]').click();
  await page.waitForURL('**/projekty');
  assert.equal(await page.evaluate(() => 'CSSViewTransitionRule' in window || document.documentElement.classList.contains('page-enter')), true, 'Opening projects should support a page transition');
  assert.equal(await page.locator('header a[href="/#opinie"]').count(), 0, 'Reviews belong on the landing page');
  assert.equal(await page.locator('header nav a[href="/"]').textContent(), 'Strona główna');
  assert.equal(await page.locator('header .brand-mark').count(), 1, 'The portfolio should use the landing-page logo mark');
  assert.equal(await page.locator('header .brand-word').textContent(), 'STFS');
  const icon = await page.request.get(base + '/favicon.svg');
  assert.equal(icon.status(), 200);
  assert.match(icon.headers()['content-type'], /image\/svg\+xml/);
  assert.equal(await page.evaluate(async () => { const image = new Image(); image.src = '/favicon.svg'; await image.decode(); const canvas = document.createElement('canvas'); canvas.width = canvas.height = 100; const context = canvas.getContext('2d'); context.drawImage(image, 0, 0); return context.getImageData(0, 0, 1, 1).data[3] === 0 && context.getImageData(50, 50, 1, 1).data[3] > 0; }), true, 'The favicon should be round with a transparent corner');
  await page.goto(base + '/projekty');
  await page.locator('.project-card').first().waitFor();
  assert.equal(await page.locator('.project-card').count(), 2);
  await page.waitForFunction(() => [...document.querySelectorAll('.project-art img')].every(img => img.complete && img.naturalWidth > 0));
  await page.locator('#projectSearch').fill('nieistniejacyprojekt');
  assert.equal(await page.locator('.project-card').count(), 0);
  assert.equal(await page.locator('#emptyProjects').isVisible(), true);
  await page.locator('#projectSearch').fill('Gonsior');
  assert.equal(await page.locator('.project-card').count(), 1);
  await page.locator('#projectSearch').fill('');
  await page.locator('.project-card').first().scrollIntoViewIfNeeded();
  await page.waitForFunction(() => [...document.querySelectorAll('.project-card')].every(node => getComputedStyle(node).opacity === '1'));
  await page.locator('#projectSearch').blur();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(tmpdir(), 'stfs-projekty-desktop.png'), fullPage: true });
  await page.locator('#coverNext').click();
  await page.waitForFunction(() => document.querySelector('#coverPosition').textContent === '2 / 2');
  await page.waitForFunction(() => {const grid=document.querySelector('#projectGrid'), card=grid.lastElementChild, rect=card.getBoundingClientRect(), view=grid.getBoundingClientRect();return Math.abs((rect.left+rect.width/2)-(view.left+view.width/2))<3;});
  assert.equal(await page.locator('#coverNext').isDisabled(), true);
  await page.locator('#coverPrev').click();
  await page.waitForFunction(() => document.querySelector('#coverPosition').textContent === '1 / 2');
  await page.waitForFunction(() => {const grid=document.querySelector('#projectGrid'), card=grid.firstElementChild, rect=card.getBoundingClientRect(), view=grid.getBoundingClientRect();return Math.abs((rect.left+rect.width/2)-(view.left+view.width/2))<3;});
  const coverBox = await page.locator('.project-card').first().boundingBox();
  await page.mouse.move(coverBox.x + coverBox.width / 2, coverBox.y + 100);
  await page.mouse.down();
  await page.mouse.move(coverBox.x + coverBox.width / 2 - 350, coverBox.y + 100, { steps: 15 });
  await page.mouse.up();
  await page.waitForFunction(() => document.querySelector('#coverPosition').textContent === '2 / 2');
  assert.ok(page.url().endsWith('/projekty'), 'Dragging must not open a project');
  await page.locator('#coverPrev').click();
  await page.waitForFunction(() => document.querySelector('#coverPosition').textContent === '1 / 2');
  const gridBox = await page.locator('#projectGrid').boundingBox();
  await page.mouse.move(gridBox.x + gridBox.width / 2, gridBox.y + 100);
  await page.mouse.wheel(0, 400);
  await page.waitForFunction(() => document.querySelector('#coverPosition').textContent === '2 / 2');
  await page.waitForFunction(() => !document.querySelector('#projectGrid').classList.contains('is-dragging'));
  await page.locator('#coverPrev').click();
  await page.waitForFunction(() => document.querySelector('#coverPosition').textContent === '1 / 2');
  await page.waitForFunction(() => {const grid=document.querySelector('#projectGrid'), card=grid.firstElementChild, rect=card.getBoundingClientRect(), view=grid.getBoundingClientRect();return Math.abs((rect.left+rect.width/2)-(view.left+view.width/2))<3;});
  await page.locator('.project-card').first().click();
  await page.locator('iframe').waitFor();
  const frame = page.frameLocator('iframe');
  await frame.locator('h1').waitFor({ state: 'attached' });
  assert.ok((await frame.locator('h1').textContent()).length > 5);
  const embedded = page.frames().find(frame => frame.url().includes('/showcases/gonsior/'));
  await page.locator('.project-canvas').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('iframe').offsetHeight > 2000);
  assert.equal(await embedded.evaluate(() => innerWidth), 1440, 'Preview should retain desktop layout');
  assert.equal(await page.locator('iframe').getAttribute('scrolling'), 'no');
  assert.equal(await page.locator('.project-annotation').count(), 5);
  assert.deepEqual(await page.locator('.project-annotation').evaluateAll(nodes => nodes.map(node => node.classList.contains('annotation--left') ? 'left' : 'right')), ['left', 'right', 'left', 'right', 'left']);
  const timedNote = page.locator('[data-anchor="oferta"]');
  assert.equal(await page.locator('.sheet-edge[aria-hidden="true"]').count(), 1, 'The folded edge should be decorative');
  assert.equal(await page.locator('.sheet-edge-label').textContent(), 'Dom Przyjęć Gonsior');
  await page.locator('.scroll-opening').evaluate(node => scrollTo({ top: node.getBoundingClientRect().top + scrollY - 400, behavior: 'instant' }));
  await page.waitForFunction(() => document.querySelector('.project-canvas').style.clipPath !== '');
  const openingHeight = await page.evaluate(() => Math.max(0, document.querySelector('.sheet-edge').getBoundingClientRect().top - document.querySelector('iframe').getBoundingClientRect().top));
  assert.ok(openingHeight < page.viewportSize().height * .4, 'The sheet should start mostly closed');
  const sectionY = await embedded.locator('#oferta').evaluate(node => node.getBoundingClientRect().top);
  const frameGeometry = await page.locator('iframe').evaluate(node => ({ top: node.getBoundingClientRect().top + scrollY, scale: node.getBoundingClientRect().width / 1440 }));
  await page.evaluate(top => scrollTo({ top, behavior: 'instant' }), frameGeometry.top + sectionY * frameGeometry.scale - page.viewportSize().height + 50);
  await embedded.waitForFunction(() => Number(getComputedStyle(document.querySelector('#oferta')).opacity) < 1);
  await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('[data-anchor="oferta"]')).opacity) < .01);
  const initialHidden = await page.locator('.project-canvas').evaluate(node => parseFloat(node.style.clipPath.split(' ')[2]));
  await timedNote.evaluate(node => scrollTo({ top: node.getBoundingClientRect().top + scrollY - innerHeight * .8, behavior: 'instant' }));
  await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('[data-anchor="oferta"] .annotation-body')).opacity) < .05);
  await timedNote.evaluate(node => scrollTo({ top: node.getBoundingClientRect().top + scrollY - innerHeight * .2, behavior: 'instant' }));
  await page.waitForFunction(() => Math.abs(document.querySelector('.sheet-edge').getBoundingClientRect().bottom - (innerHeight - 12)) < 2);
  await page.waitForFunction(hidden => parseFloat(document.querySelector('.project-canvas').style.clipPath.split(' ')[2]) < hidden, initialHidden);
  const paperEdge = await page.locator('.project-canvas').evaluate(node => {
    const bottom = node.getBoundingClientRect().bottom;
    const hidden = parseFloat(node.style.clipPath.split(' ')[2]);
    const edgeTop = document.querySelector('.sheet-edge').getBoundingClientRect().top;
    return { hidden, difference: Math.abs(bottom - hidden - edgeTop) };
  });
  assert.ok(paperEdge.hidden > 0 && paperEdge.difference < 3, 'The preview should end at the top of the roll without showing through below');
  await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('[data-anchor="oferta"] .annotation-body')).opacity) > .9);
  await embedded.waitForFunction(() => Number(getComputedStyle(document.querySelector('#oferta')).opacity) >= .99);
  await page.waitForFunction(() => document.querySelector('[data-anchor="oferta"]').classList.contains('stage-ready'));
  await page.evaluate(top => scrollTo({ top, behavior: 'instant' }), frameGeometry.top + sectionY * frameGeometry.scale - page.viewportSize().height + 50);
  await page.waitForTimeout(100);
  assert.equal(await embedded.locator('#oferta').evaluate(node => getComputedStyle(node).opacity), '1', 'An already revealed section must not fade out again when scrolling back');
  for (const chapter of await page.locator('.project-annotation').all()) {
    await chapter.evaluate(node => scrollTo({ top: node.getBoundingClientRect().top + scrollY - innerHeight * .25, behavior: 'instant' }));
    await chapter.waitFor({ state: 'visible' });
  }
  await embedded.evaluate(() => scrollTo(0, 0));
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(tmpdir(), 'stfs-projekt-desktop.png'), fullPage: true });
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const route of ['/projekty', '/projekt?slug=dom-przyjec-gonsior', '/projekt?slug=dom-przyjec-premium', '/']) {
      await page.goto(base + route);
      await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${route} overflows at ${width}px`);
    }
  }
  await page.locator('[data-reviews-grid][aria-busy="false"]').waitFor({ state: 'attached' });
  assert.equal(await page.locator('[data-reviews-status]').textContent(), 'Opinie klientów pojawią się tutaj wkrótce.');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.screenshot({ path: join(tmpdir(), 'stfs-opinie-mobile.png'), fullPage: true });
  let reviewLoads = 0;
  await page.route('**/api/reviews', route => { reviewLoads++; return route.fulfill({ json: { status: 'ok', demo: true, profileUrl: 'https://www.google.com/maps/place/test', reviews: [{author:'<script>alert(1)</script>',rating:5,text:'Przykładowa opinia',date:'test'}] } }); });
  await page.goto(base + '/#opinie');
  await page.reload();
  await page.locator('[data-reviews-grid][aria-busy="false"]').waitFor({ state: 'attached' });
  assert.equal(await page.locator('[data-reviews-demo]').isVisible(), true);
  assert.match(await page.locator('[data-reviews-demo]').textContent(), /nie dotyczą STFS/);
  assert.equal(await page.locator('.landing-reviews__card').count(), 1);
  assert.equal(await page.locator('.landing-reviews__author').textContent(), '<script>alert(1)</script>');
  assert.equal(await page.locator('.landing-reviews__author script').count(), 0, 'Review text must not execute as HTML');
  assert.equal(reviewLoads, 1);
  await page.unroute('**/api/reviews');
  await page.goto(base + '/projekt?slug=unknown');
  assert.equal(await page.locator('h1').textContent(), 'Nie znaleziono projektu.');
  await page.goto(base + '/projekty');
  assert.equal(await page.locator('a[href="/#opinie"]').count(), 0);
  const oldReviews = await page.request.get(base + '/opinie', { maxRedirects: 0 });
  assert.equal(oldReviews.status(), 308);
  assert.equal(oldReviews.headers().location, '/#opinie');
  const noJs = await browser.newPage({ javaScriptEnabled: false });
  await noJs.goto(base + '/projekty');
  assert.equal(await noJs.locator('.project-card').count(), 2, 'Project links must exist without JavaScript');
  assert.match(await noJs.locator('h1').textContent(), /Projekty stron internetowych/);
  await noJs.close();
  const protectedResponse = await page.request.get(base + '/server.mjs');
  assert.ok([403, 404].includes(protectedResponse.status()));
  const reduced = await browser.newPage({ reducedMotion: 'reduce' });
  await reduced.goto(base + '/');
  await Promise.all([reduced.waitForURL('**/projekty'), reduced.locator('.nav-links a[href="/projekty"]').click()]);
  assert.equal(await reduced.evaluate(() => document.documentElement.classList.contains('page-enter')), false, 'Reduced motion skips the page rotation');
  assert.equal(await reduced.locator('.cover-surface').last().evaluate(node => getComputedStyle(node).transform), 'none');
  await reduced.goto(base + '/projekt?slug=dom-przyjec-premium');
  assert.equal(await reduced.locator('.sheet-edge').count(), 1);
  assert.equal(await reduced.locator('.annotations-animated').count(), 0);
  assert.equal(await reduced.locator('.annotation-body').first().evaluate(node => getComputedStyle(node).opacity), '1');
  await reduced.locator('.project-canvas').scrollIntoViewIfNeeded();
  await reduced.waitForFunction(() => document.querySelector('iframe').offsetHeight > 2000);
  assert.equal(await reduced.frameLocator('iframe').locator('main > section').last().evaluate(node => getComputedStyle(node).opacity), '1');
  await reduced.close();
  const fallback = await browser.newPage();
  await fallback.addInitScript(() => { delete window.ViewTimeline; });
  await fallback.goto(base + '/projekty');
  await fallback.waitForFunction(() => getComputedStyle(document.querySelector('.cover-surface:last-child')).transform !== 'none');
  await fallback.locator('#coverNext').click();
  await fallback.waitForFunction(() => document.querySelector('#coverPosition').textContent === '2 / 2');
  await fallback.close();
  assert.deepEqual(errors, [], 'Unexpected JavaScript errors');
  console.log('PASS: projects, search, no-JS project links, embedded previews, landing reviews, 4 viewport widths and source protection.');
  console.log('Screenshots saved to: ' + tmpdir());
} finally {
  await browser.close();
}
